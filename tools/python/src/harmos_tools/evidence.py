def parse_policy(document: dict[str, Any]) -> Policy:
    """Validate the `[testing]` table; unknown keys and ambiguous selections are errors."""
    testing = _table(document.get("testing", {}), "testing", TESTING_KEYS)
    configured_limits = _table(
        testing.get("limits", {}), "testing.limits", set(CATEGORIES)
    )
    limits = dict(Policy().limits)
    for category, value in configured_limits.items():
        if not isinstance(value, int) or isinstance(value, bool) or value < 0:
            raise EvidenceError(
                f"testing.limits.{category} must be a nonnegative integer"
            )
        limits[category] = value

    rust = _table(testing.get("rust", {}), "testing.rust", RUST_KEYS)
    python = _table(testing.get("python", {}), "testing.python", PYTHON_KEYS)
    host_only = _boolean(rust, "coverage_host_only")
    base = _rust_selection(rust, host_only)
    if base.all_features and (base.features or base.no_default_features):
        raise EvidenceError(
            "testing.rust.all_features conflicts with features/no_default_features"
        )
    rust_configurations = [Configuration("default", _categories(rust), base)]
    names: set[str] = set()
    for entry in _entries(rust, "configurations", "testing.rust.configurations"):
        entry = _table(entry, "testing.rust.configurations", RUST_CONFIGURATION_KEYS)
        name = _name(entry, names)
        selection = replace(
            _rust_selection(entry, host_only),
            targets=_strings(entry, "targets", ()),
            filter=_filter(entry),
        )
        categories = _categories(entry)
        if not categories or (
            selection.all_features
            and (selection.no_default_features or selection.features)
        ):
            raise EvidenceError(
                "Rust test configurations require categories and consistent feature selection"
            )
        if selection.targets and (
            "unit" in categories or any(not item.strip() for item in selection.targets)
        ):
            raise EvidenceError(
                "Rust configuration targets name test targets and exclude unit categories"
            )
        rust_configurations.append(
            Configuration(name, categories, selection, _boolean(entry, "explicit"))
        )

    sources = _strings(python, "sources", ("src",))
    project = python.get("project", ".")
    if not sources or not isinstance(project, str):
        raise EvidenceError("testing requires nonempty Python sources")
    for path in (*sources, project):
        _relative(path, "testing.python.sources must be relative source roots")
    profile = _native_profile(python.get("native_profile"))
    python_configurations = [
        Configuration(
            "default",
            _categories(python),
            PythonSelection(project, profile, sources, _install(python)),
        )
    ]
    names = set()
    for entry in _entries(python, "configurations", "testing.python.configurations"):
        entry = _table(
            entry, "testing.python.configurations", PYTHON_CONFIGURATION_KEYS
        )
        name = _name(entry, names)
        categories = _categories(entry)
        entry_sources = _strings(entry, "sources", ())
        entry_project = entry.get("project")
        if not categories or not entry_sources or not isinstance(entry_project, str):
            raise EvidenceError(
                "Python test configurations require categories and sources"
            )
        for path in (*entry_sources, entry_project):
            _relative(
                path, "Python test configuration paths must stay within the project"
            )
        selection = PythonSelection(
            entry_project,
            _native_profile(entry.get("native_profile")),
            entry_sources,
            _install(entry),
            _filter(entry),
        )
        python_configurations.append(
            Configuration(name, categories, selection, _boolean(entry, "explicit"))
        )

    system = testing.get("system_timeout_seconds")
    if system is not None and (not _positive(system)):
        raise EvidenceError("testing requires a positive system timeout")
    overrides: list[Override] = []
    for entry in _entries(testing, "overrides", "testing.overrides"):
        entry = _table(entry, "testing.overrides", OVERRIDE_KEYS)
        if entry.get("language") != "rust":
            raise EvidenceError(
                "testing.overrides currently supports native nextest Rust selectors only"
            )
        select = entry.get("select")
        reason = entry.get("reason")
        timeout = entry.get("timeout_seconds")
        category = entry.get("category")
        if (
            category not in CATEGORIES
            or not isinstance(select, str)
            or not select.strip()
            or not isinstance(reason, str)
            or not reason.strip()
            or not isinstance(timeout, int)
            or not _positive(timeout)
        ):
            raise EvidenceError(
                "testing.overrides require a category, selector, positive timeout_seconds, "
                "and reason"
            )
        override = Override(category, "rust", select, timeout, reason)
        if any(
            (item.category, item.select) == (category, select) for item in overrides
        ):
            raise EvidenceError(f"duplicate testing override: {select}")
        overrides.append(override)
    return Policy(
        tuple(limits.items()),
        tuple(rust_configurations),
        tuple(python_configurations),
        system,
        tuple(overrides),
        _scripts(testing, "typescript"),
        _scripts(testing, "javascript"),
    )


def selections(
    policy: Policy, category: str, language: str, requested: str | None = None
) -> list[Configuration]:
    """Configurations of one language that select the category, default first.

    Explicit configurations run only when requested by name; a request runs that
    configuration alone.
    """
    configurations = {
        "rust": policy.rust,
        "python": policy.python,
        "typescript": policy.typescript,
        "javascript": policy.javascript,
    }.get(language, ())
    selected = [
        configuration
        for configuration in configurations
        if category in configuration.categories
        or (configuration.name == "default" and not configuration.categories)
    ]
    if requested is None:
        return [item for item in selected if not item.explicit]
    chosen = [item for item in selected if item.name == requested]
    if not chosen:
        raise EvidenceError(
            f"no {language} configuration {requested} selects the {category} category"
        )
    return chosen


def timeout_seconds(policy: Policy, category: str) -> int:
    """The per-test deadline of a category; system suites must declare one."""
    timeout = TIMEOUT_SECONDS.get(category, policy.system_timeout_seconds)
    if timeout is None:
        raise EvidenceError("system suites require testing.system_timeout_seconds")
    return timeout


def nextest_config(junit: str, category: str, policy: Policy, coverage: bool) -> str:
    """The nextest profile enforcing the category deadline and reviewed overrides."""
    factor = COVERAGE_FACTOR if coverage else 1
    lines = [
        "[profile.stkr]",
        "retries=0",
        "fail-fast=false",
        "slow-timeout=" + _period(timeout_seconds(policy, category) * factor),
        "[profile.stkr.junit]",
        "path=" + json.dumps(junit),
    ]
    for entry in policy.overrides:
        if entry.category == category and entry.language == "rust":
            lines += [
                "",
                "[[profile.stkr.overrides]]",
                "filter=" + json.dumps(entry.select),
                "slow-timeout=" + _period(entry.timeout_seconds * factor),
            ]
    return "\n".join(lines) + "\n"


def rust_filter(
    metadata: dict[str, Any], category: str, selection: RustSelection
) -> str:
    """The nextest filter of one category; test targets are classified by directory."""
    if category == "unit":
        # Proc-macro crates build their unit tests as `proc-macro` binaries.
        return "kind(lib) | kind(bin) | kind(proc-macro)"
    members = set(metadata.get("workspace_members", []))
    targets = []
    found: set[str] = set()
    for package in metadata.get("packages", []):
        name = package["name"]
        if package.get("id") not in members and members:
            continue
        if name in selection.exclude or (
            selection.packages and name not in selection.packages
        ):
            continue
        for target in package.get("targets", []):
            if "test" not in target.get("kind", []):
                continue
            path = target["src_path"].replace("\\", "/")
            if "/tests/acceptance/" in path:
                selected = "acceptance"
            elif "/tests/system/" in path:
                selected = "system"
            else:
                selected = "integration"
            if selected != category or (
                selection.targets and target["name"] not in selection.targets
            ):
                continue
            found.add(target["name"])
            targets.append(f"(package(={name}) & binary(={target['name']}))")
    missing = sorted(set(selection.targets) - found)
    if missing:
        raise EvidenceError(
            f"no Rust {category} test targets named {', '.join(missing)}"
        )
    if not targets:
        raise EvidenceError(f"no Rust {category} test targets discovered")
    return " | ".join(targets)


def narrowed(expression: str, selection: RustSelection) -> str:
    """A category filterset intersected with the configuration's own filter."""
    if selection.filter is None:
        return expression
    return f"({expression}) & ({selection.filter})"


def cargo_selection(selection: RustSelection) -> list[str]:
    """Locked Cargo package and feature arguments of one selection."""
    arguments = ["--locked"]
    if selection.packages:
        for package in selection.packages:
            arguments += ["--package", package]
    else:
        arguments.append("--workspace")
        for package in selection.exclude:
            arguments += ["--exclude", package]
    if selection.all_features:
        arguments.append("--all-features")
    if selection.no_default_features:
        arguments.append("--no-default-features")
    if selection.features:
        arguments += ["--features", ",".join(selection.features)]
    for target in selection.targets:
        arguments += ["--test", target]
    return arguments


def summarize(text: str, category: str, instrumented: bool) -> Record:
    """Counts and slow findings of one JUnit report; an empty or skip-only run fails."""
    cases = list(_testcases(_parse(text)))
    slow = []
    failed = skipped = 0
    for case in cases:
        skipped += _child(case, "skipped")
        failed += _child(case, "failure") or _child(case, "error")
        try:
            seconds = float(case.get("time", "0"))
        except ValueError as error:
            raise EvidenceError(f"invalid test duration: {error}") from error
        if not 0.0 <= seconds < float("inf"):
            raise EvidenceError("invalid test duration")
        if _slow(category, seconds, instrumented):
            slow.append(
                {
                    "name": case.get("name"),
                    "suite": case.get("classname"),
                    "seconds": seconds,
                }
            )
    if not cases or len(cases) == skipped:
        raise EvidenceError("required suite executed no tests")
    return {
        "tests": len(cases),
        "skipped": skipped,
        "failed": failed,
        "slow": slow,
        "instrumented": instrumented,
    }


def validate_coverage(text: str) -> None:
    """Refuse Cobertura reports without executable lines or source files."""
    root = _parse(text)
    try:
        lines = int(root.get("lines-valid", ""))
    except ValueError:
        lines = 0
    if root.tag != "coverage" or lines == 0:
        raise EvidenceError("coverage report has no executable source lines")
    if not any(node.get("filename") is not None for node in root.iter("class")):
        raise EvidenceError("coverage report has no source files")


def merge_junit(sources: Sequence[tuple[str, str]]) -> str | None:
    """Combine configuration reports into one JUnit document with one suite list.

    Named configurations prefix their suite names and test classnames so results stay
    distinguishable; the base `default` selection keeps native names. Nested suites stay
    inside their parent, and top-level cases (as `node --test` writes them) are wrapped
    in a suite named after the configuration.
    """
    if not sources:
        return None
    merged = ElementTree.Element("testsuites")
    for configuration, text in sources:
        root = _parse(text)
        if root.tag == "testsuites":
            suites = [child for child in root if child.tag == "testsuite"]
            orphans = [child for child in root if child.tag == "testcase"]
            if orphans:
                # Named configurations qualify the unnamed wrapper below.
                wrapper = ElementTree.Element("testsuite")
                if configuration == "default":
                    wrapper.set("name", configuration)
                wrapper.extend(orphans)
                suites.insert(0, wrapper)
        elif root.tag == "testsuite":
            suites = [root]
        else:
            raise EvidenceError(
                f"the {configuration} configuration report is not JUnit"
            )
        for suite in suites:
            if configuration != "default":
                _qualify(suite, "name", configuration)
                for case in suite.iter("testcase"):
                    _qualify(case, "classname", configuration)
            merged.append(suite)
    return _document(merged)


def merge_coverage(texts: Sequence[str], timestamp: int) -> str | None:
    """Combine Cobertura reports of one language; a single report is kept verbatim."""
    if len(texts) <= 1:
        return texts[0] if texts else None
    covered = valid = 0
    root = ElementTree.Element("coverage")
    sources = ElementTree.Element("sources")
    packages = ElementTree.Element("packages")
    for text in texts:
        report = _parse(text)
        lines_covered, lines_valid = line_counts(report)
        covered += lines_covered
        valid += lines_valid
        sources.extend(report.iter("source"))
        packages.extend(report.iter("package"))
    attributes = {
        "line-rate": f"{rate(covered, valid):.4f}",
        "branch-rate": "0",
        "lines-covered": str(covered),
        "lines-valid": str(valid),
        "branches-covered": "0",
        "branches-valid": "0",
        "complexity": "0",
        "version": "stkr-merged",
        "timestamp": str(timestamp),
    }
    root.attrib.update(attributes)
    root.extend([sources, packages])
    return _document(root)


def normalize_python_paths(
    text: str, root: str, authored: Sequence[tuple[str, str]]
) -> str:
    """Rewrite installed or relative coverage.py filenames to authored repository paths.

    `authored` pairs each file's import-relative suffix with its repository path.
    """
    report = _parse(text)
    reported = [node.text or "" for node in report.iter("source")]
    for node in report.iter("class"):
        filename = node.get("filename")
        if filename is None:
            raise EvidenceError("Python coverage class has no filename")
        filename = filename.replace("\\", "/")
        matches = [
            (suffix, relative)
            for suffix, relative in authored
            if filename in (relative, suffix)
            or any(
                f"{source.replace(chr(92), '/')}/{filename}".endswith(f"/{suffix}")
                for source in reported
            )
        ]
        if matches:
            specificity = max(len(suffix.split("/")) for suffix, _ in matches)
            matches = [
                match for match in matches if len(match[0].split("/")) == specificity
            ]
        if len(matches) != 1:
            raise EvidenceError(
                f"Python coverage source {filename} does not resolve uniquely to declared "
                "authored sources"
            )
        node.set("filename", matches[0][1])
    for node in report.iter("source"):
        node.text = root.replace("\\", "/")
    return _document(report)


def line_counts(root: ElementTree.Element) -> tuple[int, int]:
    """Covered and valid line counts of a Cobertura root; malformed counts are zero."""

    def count(name: str) -> int:
        try:
            return int(root.get(name, "0"))
        except ValueError:
            return 0

    return count("lines-covered"), count("lines-valid")


def rate(covered: int, valid: int) -> float:
    """Line rate, zero when nothing is executable."""
    return covered / valid if valid else 0.0


def cases(text: str, category: str, instrumented: bool) -> list[Case]:
    """Cases of one report: failures first, then slow findings, then by descending duration."""
    result = []
    root = _parse(text)
    parents = {child: parent for parent in root.iter() for child in parent}
    for node in _testcases(root):
        if _child(node, "failure") or _child(node, "error"):
            outcome = "failed"
        elif _child(node, "skipped"):
            outcome = "skipped"
        else:
            outcome = "passed"
        try:
            seconds = float(node.get("time", "0"))
        except ValueError:
            seconds = 0.0
        if not 0.0 <= seconds < float("inf"):
            seconds = 0.0
        suite = parents.get(node)
        package = node.get("classname") or (
            suite.get("name") if suite is not None else None
        )
        result.append(
            Case(
                package=package or "",
                name=node.get("name", ""),
                outcome=outcome,
                seconds=seconds,
                slow=_slow(category, seconds, instrumented),
            )
        )
    result.sort(
        key=lambda case: (OUTCOMES.index(case.outcome), not case.slow, -case.seconds)
    )
    return result


def render_tests(
    manifest: Record,
    reports: Sequence[tuple[str, str, str]],
    coverage: Sequence[tuple[str, str]],
    limits: tuple[tuple[str, int], ...] = Policy().limits,
) -> tuple[str, str]:
    """Render `tests.csv` and `tests.md` from flat reports and their manifest entries."""
    suites = []
    for category, language, text in reports:
        entry = manifest.get("tests", {}).get(f"{category}-{language}", {})
        suites.append(
            Suite(
                category=category,
                language=language,
                revision=entry.get("revision"),
                deadline_ms=entry.get("deadline_ms"),
                cases=cases(text, category, bool(entry.get("coverage", False))),
            )
        )
    lines = []
    for language, text in coverage:
        covered, valid = line_counts(_parse(text))
        lines.append(
            (language, covered, valid, manifest.get("coverage", {}).get(language))
        )
    return _tests_csv(suites), _tests_markdown(suites, lines, limits)


def coverage_environment(text: str) -> list[tuple[str, str]]:
    """Parse `cargo llvm-cov show-env --cmd` output as data, never as shell code."""
    environment = []
    for line in text.splitlines():
        if not line:
            continue
        if not line.startswith("set ") or "=" not in line:
            raise EvidenceError("unsupported cargo-llvm-cov environment output")
        key, value = line.removeprefix("set ").split("=", 1)
        if not key or not all(
            c.isascii() and (c.isupper() or c.isdigit() or c == "_") for c in key
        ):
            raise EvidenceError("invalid native coverage environment key")
        environment.append((key, value))
    return environment


def criterion_row(
    domain: str, identity: Record, estimates: Record, sample: Record
) -> Row:
    """One Criterion result with a nearest-rank p95 of per-iteration sample times."""
    name = identity.get("full_id")
    median = estimates.get("median", {}).get("point_estimate")
    if not isinstance(name, str):
        raise EvidenceError("Criterion result has no benchmark id")
    if not isinstance(median, int | float):
        raise EvidenceError("Criterion result has no median")
    per_iteration = [
        time_ / count
        for time_, count in zip(
            sample.get("times", []), sample.get("iters", []), strict=False
        )
        if count
    ]
    return Row(
        language="rust",
        domain=domain,
        name=name,
        samples=len(per_iteration),
        median_ns=float(median),
        mean_ns=estimates.get("mean", {}).get("point_estimate"),
        p95_ns=percentile(per_iteration, 0.95),
        stddev_ns=estimates.get("std_dev", {}).get("point_estimate"),
    )


def pytest_benchmark(text: str) -> list[Row]:
    """Rows of a pytest-benchmark JSON report, in nanoseconds, by benchmark domain."""
    try:
        report = json.loads(text)
    except json.JSONDecodeError as error:
        raise EvidenceError(f"invalid pytest-benchmark report: {error}") from error
    rows = []
    for benchmark in report.get("benchmarks") or []:
        fullname = benchmark.get("fullname")
        if not isinstance(fullname, str):
            raise EvidenceError("pytest-benchmark result has no name")
        relative = fullname.replace("\\", "/").removeprefix("benchmarks/")
        domain, separator, name = relative.partition("/")
        if not separator or "::" in domain:
            domain, name = "default", relative
        stats = benchmark.get("stats", {})
        median = stats.get("median")
        if not isinstance(median, int | float):
            raise EvidenceError("pytest-benchmark result has no median")
        data = [
            value * 1e9
            for value in stats.get("data", [])
            if isinstance(value, int | float)
        ]
        rows.append(
            Row(
                language="python",
                domain=domain,
                name=name,
                samples=stats.get("rounds"),
                median_ns=median * 1e9,
                mean_ns=_nanoseconds(stats.get("mean")),
                p95_ns=percentile(data, 0.95),
                stddev_ns=_nanoseconds(stats.get("stddev")),
            )
        )
    if not rows:
        raise EvidenceError("pytest-benchmark produced no results")
    return rows


def percentile(values: Sequence[float], quantile: float) -> float | None:
    """Nearest-rank percentile of the finite values."""
    finite = sorted(value for value in values if math.isfinite(value))
    if not finite:
        return None
    index = min(max(math.ceil(len(finite) * quantile), 1), len(finite)) - 1
    return finite[index]


def merge_bench(previous: str, language: str, measured: Sequence[Row]) -> list[Row]:
    """Replace one language's rows, keep other languages, and compare with the last run."""
    rows = parse_bench(previous)
    medians = {(row.language, row.domain, row.name): row.median_ns for row in rows}
    merged = [row for row in rows if row.language != language]
    for row in measured:
        merged.append(
            replace(
                row,
                previous_median_ns=medians.get((row.language, row.domain, row.name)),
            )
        )
    merged.sort(key=lambda row: (row.language, row.domain, row.name))
    return merged


def parse_bench(text: str) -> list[Row]:
    """Read a previous `bench.csv`; malformed rows are dropped rather than trusted."""
    rows = []
    for line in text.splitlines()[1:]:
        fields = _split(line)
        if len(fields) != 11:
            continue
        median = _float(fields[4])
        if median is None:
            continue
        rows.append(
            Row(
                language=fields[0],
                domain=fields[1],
                name=fields[2],
                samples=_int(fields[3]),
                median_ns=median,
                mean_ns=_float(fields[5]),
                p95_ns=_float(fields[6]),
                stddev_ns=_float(fields[7]),
                peak_bytes=_int(fields[8]),
                previous_median_ns=_float(fields[9]),
            )
        )
    return rows


def bench_csv(rows: Sequence[Row]) -> str:
    """Render `bench.csv`."""
    lines = [BENCH_HEADER]
    for row in rows:
        change = _change(row)
        lines.append(
            ",".join(
                [
                    row.language,
                    csv_field(row.domain),
                    csv_field(row.name),
                    _optional(row.samples),
                    f"{row.median_ns:.1f}",
                    _optional_float(row.mean_ns),
                    _optional_float(row.p95_ns),
                    _optional_float(row.stddev_ns),
                    _optional(row.peak_bytes),
                    _optional_float(row.previous_median_ns),
                    "" if change is None else f"{change:.2f}",
                ]
            )
        )
    return "\n".join(lines) + "\n"


def bench_markdown(rows: Sequence[Row]) -> str:
    """Render `bench.md`: one table per language and domain."""
    text = (
        "# Benchmark Results\n\nLatest run of each language; change compares medians with the "
        "previous run. Every row is in `bench.csv`.\n"
    )
    if not rows:
        text += "\nNo benchmark results are retained.\n"
    current = None
    for row in rows:
        if current != (row.language, row.domain):
            current = (row.language, row.domain)
            text += (
                f"\n## {title(row.language)} {markdown_cell(row.domain)}\n\n"
                "| Benchmark | Samples | Median | Mean | p95 | Std Dev | Previous Median "
                "| Change |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n"
            )
        change = _change(row)
        cells = [
            markdown_cell(row.name),
            _optional(row.samples),
            _duration(row.median_ns),
            _optional_duration(row.mean_ns),
            _optional_duration(row.p95_ns),
            _optional_duration(row.stddev_ns),
            _optional_duration(row.previous_median_ns),
            "" if change is None else f"{change:+.1f}%",
        ]
        text += "| " + " | ".join(cells) + " |\n"
    return text


def csv_field(value: str) -> str:
    """Quote a CSV field only when its content requires it."""
    if any(character in value for character in ',"\n\r'):
        return '"' + value.replace('"', '""') + '"'
    return value


def markdown_cell(value: str) -> str:
    """Escape a Markdown table cell."""
    return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def title(value: str) -> str:
    """Capitalize the first character only."""
    return value[:1].upper() + value[1:]


def run(
    root: Path,
    category: str,
    language: str,
    coverage: bool,
    configuration: str | None = None,
    rust_arguments: tuple[bool, bool, tuple[str, ...]] | None = None,
) -> None:
    """Run a category with native tools; flat evidence survives failing tests.

    Script runners have no instrumentation adapter: a coverage request runs them
    uninstrumented and records that coverage was not measured.
    """
    policy = parse_policy(_config(root))
    if rust_arguments is not None:
        all_features, no_default_features, features = rust_arguments
        if language != "rust" or all_features and (no_default_features or features):
            raise EvidenceError(
                "Rust feature arguments require a consistent Rust selection"
            )
        default = policy.rust[0]
        if not isinstance(default.selection, RustSelection):
            raise EvidenceError("default Rust configuration must select a Rust runner")
        selection = replace(
            default.selection,
            all_features=all_features,
            no_default_features=no_default_features,
            features=features,
        )
        policy = replace(
            policy, rust=(replace(default, selection=selection), *policy.rust[1:])
        )

    requested_coverage = coverage
    coverage = coverage and language not in SCRIPT_LANGUAGES
    key = f"{category}-{language}"
    with Lock(_state(root) / f"testing-{key}.lock"):
        with Lock(_state(root) / "evidence.lock", wait_seconds=30):
            _clear_tests(root, policy, key, language)
        _directory(root)
        mode = "coverage" if coverage else "default"
        raw = root / "target" / "validation" / mode / category / language
        _fresh(raw)
        started = int(time.time())
        clock = time.monotonic()
        selected: list[Configuration] = []
        records: list[Record] = []

        def execute() -> None:
            if category == "unit" and dict(policy.limits)["unit"] == 0:
                raise EvidenceError(
                    "unit tests exceed the project limit of 0; use stkr project purge unit-tests"
                )
            selected.extend(selections(policy, category, language, configuration))
            if coverage and language == "rust":
                # Shared Compilation, Exclusive Measurement Ownership.
                with Lock(_state(root) / "coverage-rust.lock", wait_seconds=30):
                    environment = dict(os.environ)
                    target = root / "target/validation/cargo/coverage"
                    environment["CARGO_TARGET_DIR"] = str(target)
                    environment["CARGO_LLVM_COV_TARGET_DIR"] = str(target)
                    environment["CARGO_LLVM_COV_BUILD_DIR"] = str(target)
                    if not _execute(
                        ["cargo", "llvm-cov", "clean", "--profraw-only"],
                        root,
                        environment=environment,
                    ):
                        raise EvidenceError("coverage measurement cleanup failed")
                    _run_selections(
                        root,
                        policy,
                        raw,
                        selected,
                        (category, language),
                        coverage,
                        records,
                    )
            else:
                _run_selections(
                    root, policy, raw, selected, (category, language), coverage, records
                )

        failure = _attempt(execute)

        with Lock(_state(root) / "evidence.lock", wait_seconds=30):
            # Publish Flat Evidence, Even For Failed Runs
            names = [configuration.name for configuration in selected]
            junit = [
                (name, (raw / name / "junit.xml").read_text(encoding="utf-8"))
                for name in names
                if (raw / name / "junit.xml").is_file()
            ]
            key = f"{category}-{language}"
            published = _attempt(
                lambda: _flat(root, f"tests-{key}.xml", merge_junit(junit))
            )
            coverage_published = False
            if coverage:
                texts = [
                    path.read_text(encoding="utf-8")
                    for name in names
                    for path in (
                        raw / name / "coverage.xml",
                        raw / name / "native-coverage.xml",
                    )
                    if path.is_file()
                ]
                merged = _attempt(lambda: merge_coverage(texts, int(time.time())))
                if isinstance(merged, EvidenceError):
                    published = published or merged
                else:
                    coverage_published = merged is not None
                    published = published or _attempt(
                        lambda: _flat(root, f"coverage-{language}.xml", merged)
                    )
            deadline = _attempt(lambda: timeout_seconds(policy, category))
            entry = {
                "category": category,
                "language": language,
                "coverage": coverage,
                "coverage_requested": requested_coverage,
                "requested_configuration": configuration,
                "outcome": "failed" if failure or published else "passed",
                "error": _message(failure),
                "report_error": _message(published),
                "revision": revision(root),
                "platform": _platform(),
                "architecture": _architecture(),
                "tools": _tools(root, policy, (category, language), coverage),
                "deadline_ms": None
                if isinstance(deadline, EvidenceError)
                else deadline * 1000 * (COVERAGE_FACTOR if coverage else 1),
                "started_unix_seconds": started,
                "finished_unix_seconds": int(time.time()),
                "elapsed_seconds_including_build": time.monotonic() - clock,
                "native_output": raw.relative_to(root).as_posix(),
                "configurations": records,
            }
            _update(root, "tests", key, entry)
            if coverage_published:
                _update(root, "coverage", language, category)
            _publish_tests(root)
    error = failure or published
    if error is not None:
        raise error


def bench(root: Path, language: str) -> None:
    """Run every benchmark of one language and publish `bench.csv`, `bench.md`, and the
    manifest entry; native output stays in the build tree and the run log in `bench.log`."""
    policy = parse_policy(_config(root))
    with Lock(_state(root) / "bench.lock"):
        with Lock(_state(root) / "evidence.lock", wait_seconds=30):
            baseline = _clear_bench(root, language)
        _directory(root)
        log = _state(root) / BENCH_LOG
        log.write_text("", encoding="utf-8")
        started = int(time.time())
        clock = time.monotonic()
        rows: list[Row] = []

        def measure() -> None:
            if language == "rust":
                rows.extend(_bench_rust(root, log))
            elif language == "python":
                rows.extend(_bench_python(root, policy, log))
            else:
                raise EvidenceError(f"no native benchmark adapter for {language}")

        failure = _attempt(measure)
        published = _attempt(
            lambda: _publish_bench(root, language, [] if failure else rows, baseline)
        )
        entry = {
            "language": language,
            "outcome": "failed" if failure or published else "passed",
            "error": _message(failure),
            "report_error": _message(published),
            "benchmarks": 0 if failure else len(rows),
            "revision": revision(root),
            "platform": _platform(),
            "architecture": _architecture(),
            "started_unix_seconds": started,
            "finished_unix_seconds": int(time.time()),
            "elapsed_seconds_including_build": time.monotonic() - clock,
            "log": f"{STATE}/{BENCH_LOG}",
        }
        with Lock(_state(root) / "evidence.lock", wait_seconds=30):
            _update(root, "benchmarks", language, entry)
    error = failure or published
    if error is not None:
        raise error


def revision(root: Path) -> str | None:
    """The checked-out Git commit."""
    text = _query(root, ["git", "rev-parse", "--verify", "HEAD"])
    return text.strip() if text else None


def main(arguments: Sequence[str] | None = None) -> int:
    """Command line entry point; failures exit nonzero after publishing evidence."""
    parser = argparse.ArgumentParser(
        prog="evidence",
        description="Publish flat validation evidence from native runners.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        help="project root; defaults to the evidence configuration owner",
    )
    commands = parser.add_subparsers(dest="command", required=True)
    tests = commands.add_parser("run", help="run one test category of one language")
    tests.add_argument("category", choices=CATEGORIES)
    tests.add_argument("language", choices=LANGUAGES)
    tests.add_argument(
        "--coverage", action="store_true", help="instrument the same selection"
    )
    tests.add_argument(
        "--configuration",
        help="run only this named configuration, including explicit ones",
    )
    tests.add_argument("--all-features", action="store_true")
    tests.add_argument("--no-default-features", action="store_true")
    tests.add_argument(
        "--features", help="comma-separated features for the default configuration"
    )
    benchmarks = commands.add_parser(
        "bench", help="run every benchmark of one language"
    )
    benchmarks.add_argument("language", choices=("rust", "python"))
    options = parser.parse_args(arguments)
    root = (options.root or _project_root(Path.cwd())).resolve()
    try:
        if options.command == "run":
            coverage = options.coverage or os.environ.get(COVERAGE_VARIABLE) == "1"
            run(
                root,
                options.category,
                options.language,
                coverage,
                options.configuration,
                (
                    options.all_features,
                    options.no_default_features,
                    tuple(options.features.split(",")) if options.features else (),
                )
                if options.all_features
                or options.no_default_features
                or options.features
                else None,
            )
        else:
            bench(root, options.language)
    except EvidenceError as error:
        print(f"evidence: {error}", file=sys.stderr)
        return 1
    return 0


