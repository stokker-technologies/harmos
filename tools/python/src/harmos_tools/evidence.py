def _duration(nanoseconds: float) -> str:
    if nanoseconds >= 1e9:
        return f"{nanoseconds / 1e9:.3f} s"
    if nanoseconds >= 1e6:
        return f"{nanoseconds / 1e6:.3f} ms"
    if nanoseconds >= 1e3:
        return f"{nanoseconds / 1e3:.3f} µs"
    return f"{nanoseconds:.1f} ns"


def _optional_duration(value: float | None) -> str:
    return "" if value is None else _duration(value)


