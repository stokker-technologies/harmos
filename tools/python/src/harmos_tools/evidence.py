@dataclass
class Lock:
    """Exclusive run ownership below private state, released when the run ends."""

    path: Path
    wait_seconds: float = 0
    held: bool = field(default=False, init=False)

    def __enter__(self) -> "Lock":
        deadline = time.monotonic() + self.wait_seconds
        while True:
            try:
                with self.path.open("x", encoding="utf-8"):
                    pass
                break
            except FileExistsError as error:
                if time.monotonic() >= deadline:
                    raise EvidenceError(
                        f"{self.path.name} is held; another run may own it, check for a "
                        "live owner before removing it"
                    ) from error
                time.sleep(0.01)
        self.held = True
        return self

    def __exit__(self, *_: object) -> None:
        if self.held:
            self.path.unlink(missing_ok=True)


