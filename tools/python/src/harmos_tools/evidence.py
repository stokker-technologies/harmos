def _docs_version(value: str, policy: dict[str, Any]) -> bool:
    match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)(?:-([^+]+))?(?:\+.+)?", value)
    if match is None:
        raise EvidenceError(f"invalid Cargo package version: {value!r}")
    return (int(match.group(1)) > 0 or policy.get("allow_unstable", False)) and (
        match.group(4) is None or policy.get("allow_prerelease", True)
    )


def _table(value: object, name: str, keys: set[str]) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise EvidenceError(f"invalid testing policy: {name} must be a table")
    unknown = sorted(set(value) - keys)
    if unknown:
        raise EvidenceError(
            f"invalid testing policy: unknown {name} keys {', '.join(unknown)}"
        )
    return value


def _entries(table: dict[str, Any], key: str, name: str) -> list[Any]:
    value = table.get(key, [])
    if not isinstance(value, list):
        raise EvidenceError(
            f"invalid testing policy: {name} must be an array of tables"
        )
    return value


def _boolean(table: dict[str, Any], key: str) -> bool:
    value = table.get(key, False)
    if not isinstance(value, bool):
        raise EvidenceError(f"invalid testing policy: {key} must be a boolean")
    return value


def _strings(
    table: dict[str, Any], key: str, default: tuple[str, ...]
) -> tuple[str, ...]:
    value = table.get(key, list(default))
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise EvidenceError(
            f"invalid testing policy: {key} must be an array of strings"
        )
    return tuple(value)


def _categories(table: dict[str, Any]) -> tuple[str, ...]:
    categories = _strings(table, "categories", ())
    if any(category not in CATEGORIES for category in categories):
        raise EvidenceError("invalid testing policy: unknown test category")
    return categories


def _rust_selection(table: dict[str, Any], host_only: bool) -> RustSelection:
    selection = RustSelection(
        all_features=_boolean(table, "all_features"),
        no_default_features=_boolean(table, "no_default_features"),
        features=_strings(table, "features", ()),
        packages=_strings(table, "packages", ()),
        exclude=_strings(table, "exclude", ()),
        coverage_host_only=host_only,
    )
    if (selection.packages and selection.exclude) or any(
        not name.strip() for name in (*selection.packages, *selection.exclude)
    ):
        raise EvidenceError(
            "Rust testing selects packages or excludes workspace packages, never both"
        )
    return selection


def _filter(table: dict[str, Any]) -> str | None:
    value = table.get("filter")
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip() or value.startswith("-"):
        raise EvidenceError(
            "invalid testing policy: filter must be a nonempty expression, not an option"
        )
    return value


def _install(table: dict[str, Any]) -> str:
    value = table.get("install", INSTALLS[0])
    if value not in INSTALLS:
        raise EvidenceError(
            f"invalid testing policy: install must be one of {', '.join(INSTALLS)}"
        )
    return value


def _scripts(testing: dict[str, Any], language: str) -> tuple[Configuration, ...]:
    """One runner per category; each category is its own `default` configuration."""
    name = f"testing.{language}"
    table = _table(testing.get(language, {}), name, set(CATEGORIES))
    configurations = []
    for category in CATEGORIES:
        if category not in table:
            continue
        entry = _table(table[category], f"{name}.{category}", SCRIPT_KEYS)
        command = _strings(entry, "command", ())
        directory = entry.get("directory", ".")
        timeout = entry.get("timeout_seconds")
        if (
            not command
            or not command[0].strip()
            or not any(JUNIT_PLACEHOLDER in argument for argument in command)
            or not isinstance(directory, str)
            or (timeout is not None and not _positive(timeout))
        ):
            raise EvidenceError(
                f"{name}.{category} requires a command writing JUnit to "
                f"{JUNIT_PLACEHOLDER}, a relative directory, and a positive timeout"
            )
        _relative(
            directory, f"{name}.{category} directory must stay within the project"
        )
        runner = ScriptRunner(directory, command, timeout)
        configurations.append(Configuration("default", (category,), runner))
    return tuple(configurations)


def _name(table: dict[str, Any], names: set[str]) -> str:
    name = table.get("name")
    if (
        not isinstance(name, str)
        or not name
        or not all(c.isascii() and (c.isalnum() or c in "-_") for c in name)
        or name == "default"
        or name != name.lower()
        or name in RESERVED_NAMES
        or _device(name)
        or name in names
    ):
        raise EvidenceError(
            "test configuration names must be unique portable names other than default"
        )
    names.add(name)
    return name


def _native_profile(profile: object) -> str | None:
    if profile is None:
        return None
    name = profile.lower() if isinstance(profile, str) else ""
    if (
        not isinstance(profile, str)
        or not profile
        or profile.startswith("-")
        or not all(c.isascii() and (c.isalnum() or c in "-_") for c in profile)
        or name in RESERVED_PROFILES
        or name.startswith("cargo")
        or _device(name)
    ):
        raise EvidenceError(
            "testing.python.native_profile must be a nonempty portable Cargo profile name"
        )
    return profile


def _device(name: str) -> bool:
    return len(name) == 4 and name[:3] in ("com", "lpt") and name[3] in "123456789"


def _relative(path: str, message: str) -> None:
    candidate = Path(path)
    if (
        not path
        or candidate.is_absolute()
        or path.startswith(("/", "\\"))
        or ".." in candidate.parts
    ):
        raise EvidenceError(message)


def _positive(value: object) -> bool:
    return (
        isinstance(value, int)
        and not isinstance(value, bool)
        and 0 < value <= 2**64 // 5
    )


def _period(seconds: int) -> str:
    return "{period='" + str(seconds) + "s',terminate-after=1}"


def _parse(text: str) -> ElementTree.Element:
    # Coverage.py emits a DOCTYPE; expat never fetches external entities.
    try:
        return ElementTree.fromstring(text)
    except ElementTree.ParseError as error:
        raise EvidenceError(f"invalid validation XML: {error}") from error


def _document(root: ElementTree.Element) -> str:
    body = ElementTree.tostring(root, encoding="unicode")
    return f'<?xml version="1.0" encoding="UTF-8"?>\n{body}\n'


def _testcases(root: ElementTree.Element) -> Iterator[ElementTree.Element]:
    return root.iter("testcase")


def _child(node: ElementTree.Element, tag: str) -> bool:
    return node.find(tag) is not None


def _slow(category: str, seconds: float, instrumented: bool) -> bool:
    limit = SLOW_MILLISECONDS.get(category)
    return not instrumented and limit is not None and seconds * 1000.0 > limit


def _qualify(node: ElementTree.Element, attribute: str, configuration: str) -> None:
    existing = node.get(attribute)
    node.set(
        attribute, configuration if existing is None else f"{configuration}/{existing}"
    )


def _milliseconds(seconds: float) -> int:
    return int(seconds * 1000.0 + 0.5)


def _tests_csv(suites: Sequence[Suite]) -> str:
    lines = [TESTS_HEADER]
    for suite in suites:
        deadline = "" if suite.deadline_ms is None else str(suite.deadline_ms)
        for case in suite.cases:
            lines.append(
                ",".join(
                    [
                        suite.category,
                        suite.language,
                        csv_field(case.package),
                        csv_field(case.name),
                        case.outcome,
                        str(_milliseconds(case.seconds)),
                        deadline,
                        "true" if case.slow else "false",
                    ]
                )
            )
    return "\n".join(lines) + "\n"


def _tests_markdown(
    suites: Sequence[Suite],
    coverage: Sequence[tuple[str, int, int, str | None]],
    limits: tuple[tuple[str, int], ...] = Policy().limits,
) -> str:
    text = (
        "# Test Results\n\nLatest run of each category and language. Every case is in "
        "`tests.csv`; native JUnit is in `tests-<category>-<language>.xml`.\n"
    )
    if not suites:
        text += "\nNo test reports are retained.\n"
    for suite in suites:
        counts = {outcome: 0 for outcome in OUTCOMES}
        for case in suite.cases:
            counts[case.outcome] += 1
        slow = sum(case.slow for case in suite.cases)
        text += (
            f"\n## {title(suite.category)} {title(suite.language)}\n\n"
            f"Revision `{suite.revision or 'unknown'}`: {len(suite.cases)} tests, "
            f"{counts['passed']} passed, {counts['failed']} failed, {counts['skipped']} "
            f"skipped, {slow} slow."
        )
        limit = dict(limits)[suite.category]
        scope = "project"
        text += f" Authored test limit: {limit} across all files and languages in the {scope}; executed cases may expand parameterized tests."
        grouped: dict[str, int] = {}
        for case in suite.cases:
            grouped[case.package] = grouped.get(case.package, 0) + 1
        text += (
            "\n\n| Target | Executed Tests | Authored Limit |\n| --- | ---: | ---: |\n"
        )
        if suite.category in ("acceptance", "system"):
            text += f"| Repository | {len(suite.cases)} | {limit} |\n"
        else:
            for package, count in sorted(grouped.items()):
                text += f"| {markdown_cell(package)} | {count} | {limit} |\n"
        if suite.deadline_ms is not None:
            text += f" Deadline {suite.deadline_ms} ms per test."
        text += (
            "\n\n| Outcome | Package | Test | Duration (ms) | Slow |\n"
            "| --- | --- | --- | ---: | --- |\n"
        )
        for case in suite.cases:
            cells = [
                case.outcome,
                markdown_cell(case.package),
                markdown_cell(case.name),
                str(_milliseconds(case.seconds)),
                "yes" if case.slow else "",
            ]
            text += "| " + " | ".join(cells) + " |\n"
    if coverage:
        text += (
            "\n## Coverage\n\n| Language | Source Run | Lines Covered | Lines Valid | Line Rate |\n"
            "| --- | --- | ---: | ---: | ---: |\n"
        )
        for language, covered, valid, source in coverage:
            text += (
                f"| {language} | {source or 'unknown'} | {covered} | {valid} | "
                f"{rate(covered, valid) * 100.0:.1f}% |\n"
            )
    return text


def _nanoseconds(seconds: object) -> float | None:
    return seconds * 1e9 if isinstance(seconds, int | float) else None


def _change(row: Row) -> float | None:
    previous = row.previous_median_ns
    if previous is None or previous <= 0.0:
        return None
    return (row.median_ns - previous) / previous * 100.0


