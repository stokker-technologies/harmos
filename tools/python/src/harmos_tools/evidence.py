def _real_directories(root: Path, relative: str, message: str) -> Path:
    """Create each component, refusing symlinked or non-directory components."""
    directory = root
    for part in Path(relative).parts:
        directory = directory / part
        if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
            raise EvidenceError(message)
        directory.mkdir(exist_ok=True)
        if directory.is_symlink() or not directory.is_dir():
            raise EvidenceError(message)
    return directory


def _state(root: Path) -> Path:
    message = "private state must be a real directory"
    state = _real_directories(root, STATE, message)
    _real_directories(root, f"{STATE}/logs", message)
    return state


def _directory(root: Path, benchmark: bool = False) -> Path:
    return _real_directories(
        root,
        BENCHMARKS if benchmark else VALIDATION,
        "validation evidence directory must be a real directory, not a symlink",
    )


def _publish(root: Path, name: str, text: str, benchmark: bool = False) -> None:
    """Atomically replace one flat evidence file through its `.tmp` sibling."""
    directory = _directory(root, benchmark)
    target = directory / name
    if target.is_symlink() or (target.exists() and not target.is_file()):
        raise EvidenceError(f"validation evidence {name} must be a regular file")
    temporary = directory / f"{name}.tmp"
    if temporary.is_symlink() or (temporary.exists() and not temporary.is_file()):
        raise EvidenceError("temporary validation evidence must be a regular file")
    # An interrupted publication can leave this single bounded temporary file.
    temporary.unlink(missing_ok=True)
    try:
        with temporary.open("x", encoding="utf-8", newline="\n") as file:
            file.write(text)
        os.replace(temporary, target)
    except OSError:
        temporary.unlink(missing_ok=True)
        raise


def _retract(root: Path, name: str, benchmark: bool = False) -> None:
    """Remove a flat evidence file whose run produced no fresh replacement."""
    path = root / (BENCHMARKS if benchmark else VALIDATION) / name
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.exists():
        raise EvidenceError(f"validation evidence {name} must be a regular file")


def _flat(root: Path, name: str, text: str | None) -> None:
    if text is None:
        _retract(root, name)
    else:
        _publish(root, name, text)


def _manifest(root: Path, benchmark: bool = False) -> Record | None:
    """The current run manifest; an unreadable manifest is replaced, never trusted."""
    path = root / (BENCHMARKS if benchmark else VALIDATION) / "latest.json"
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise EvidenceError("validation evidence must be a regular file")
    if not path.exists():
        return None
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError):
        return None
    return value if isinstance(value, dict) else None


def _clear_tests(root: Path, policy: Policy, key: str, language: str) -> None:
    """Clear this run and retired categories while holding publication ownership."""
    manifest = _manifest(root) or {"schema_version": 1}
    manifest["host"] = {"os": _platform(), "arch": _architecture()}
    tests = manifest.get("tests", {})
    tests = tests if isinstance(tests, dict) else {}
    document = _config(root).get("testing", {})
    configured = {
        f"{category}-{candidate}"
        for candidate in LANGUAGES
        if candidate in document
        for category in CATEGORIES
        if (category != "unit" or dict(policy.limits)["unit"] > 0)
        if any(
            category
            in (
                selection.categories
                or tuple(
                    category
                    for category in ("unit", "integration")
                    if category != "unit" or dict(policy.limits)["unit"] > 0
                )
            )
            for selection in getattr(policy, candidate)
        )
    }
    configured.add(key)
    for candidate in LANGUAGES:
        for category in CATEGORIES:
            retained = f"{category}-{candidate}"
            if retained not in configured:
                _retract(root, f"tests-{retained}.xml")
    for retained in list(tests):
        if retained == key or retained not in configured:
            tests.pop(retained)
            _retract(root, f"tests-{retained}.xml")
    _retract(root, f"tests-{key}.xml")
    coverage = manifest.get("coverage", {})
    coverage = coverage if isinstance(coverage, dict) else {}
    for candidate, owner in list(coverage.items()):
        if candidate == language or f"{owner}-{candidate}" not in configured:
            coverage.pop(candidate)
            _retract(root, f"coverage-{candidate}.xml")
    manifest["tests"] = tests
    manifest["coverage"] = coverage
    _publish(root, "latest.json", json.dumps(manifest, indent=2))
    _publish_tests(root)


def _update(root: Path, section: str, key: str, value: object) -> None:
    """Replace one runner-owned entry of the run manifest, preserving every other field."""
    benchmark = section == "benchmarks"
    manifest = _manifest(root, benchmark) or {
        "schema_version": 1,
        "host": {"os": _platform(), "arch": _architecture()},
    }
    if not isinstance(manifest.get(section), dict):
        manifest[section] = {}
    manifest[section][key] = value
    _publish(root, "latest.json", json.dumps(manifest, indent=2), benchmark)


