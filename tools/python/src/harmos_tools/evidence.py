def _fresh(path: Path) -> None:
    """Replace a native output directory, refusing symlinked ancestors."""
    for ancestor in (path, *path.parents):
        if ancestor.is_symlink() or (ancestor.exists() and not ancestor.is_dir()):
            raise EvidenceError(
                f"refusing non-directory or symlink report ancestor {ancestor}"
            )
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)


def _executable(name: str) -> str:
    """Resolve a native tool to a full path so Windows command shims also run."""
    resolved = shutil.which(name)
    if resolved is None:
        raise EvidenceError(f"{name} is not installed; install it through mise")
    return resolved


def _command(arguments: Sequence[str]) -> list[str]:
    return [_executable(arguments[0]), *arguments[1:]]


def _execute(
    arguments: Sequence[str], cwd: Path, environment: dict[str, str] | None = None
) -> bool:
    try:
        return (
            subprocess.run(
                _command(arguments), cwd=cwd, env=environment, check=False
            ).returncode
            == 0
        )
    except OSError as error:
        raise EvidenceError(f"execute {arguments[0]}: {error}") from error


def _query(root: Path, arguments: Sequence[str]) -> str | None:
    """A short read-only command's standard output, or None when it is unavailable."""
    executable = shutil.which(arguments[0])
    if executable is None:
        return None
    try:
        result = subprocess.run(
            [executable, *arguments[1:]],
            cwd=root,
            capture_output=True,
            text=True,
            timeout=COMMAND_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout if result.returncode == 0 else None


def _tools(
    root: Path, policy: Policy, target: tuple[str, str], coverage: bool
) -> dict[str, str | None]:
    """Native tool versions; unavailable tools are recorded as absent, never guessed."""
    category, language = target
    if language == "rust":
        commands = [
            ("cargo", ["cargo", "--version"]),
            ("cargo-nextest", ["cargo", "nextest", "--version"]),
        ]
    elif language == "python":
        commands = [("uv", ["uv", "--version"])]
    else:
        commands = [("node", ["node", "--version"])]
        runners = {
            item.selection.command[0]
            for item in selections(policy, category, language)
            if isinstance(item.selection, ScriptRunner)
        }
        commands += [(name, [name, "--version"]) for name in sorted(runners - {"node"})]
    if coverage:
        commands.append(("cargo-llvm-cov", ["cargo", "llvm-cov", "--version"]))
    versions = {}
    for name, arguments in commands:
        text = _query(root, arguments)
        versions[name] = text.splitlines()[0].strip() if text and text.strip() else None
    return versions


def _metadata(root: Path) -> dict[str, Any]:
    try:
        result = subprocess.run(
            _command(["cargo", "metadata", "--no-deps", "--format-version", "1"]),
            cwd=root,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as error:
        raise EvidenceError(f"test target inventory: {error}") from error
    if result.returncode != 0:
        raise EvidenceError(f"test target inventory: {result.stderr.strip()}")
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise EvidenceError(f"test target inventory: {error}") from error


def _run_selections(
    root: Path,
    policy: Policy,
    raw: Path,
    selected: Sequence[Configuration],
    target: tuple[str, str],
    coverage: bool,
    records: list[Record],
) -> None:
    category, language = target
    if not selected:
        raise EvidenceError("no test configuration selects this category and language")
    failures = []
    for configuration in selected:
        output = raw / configuration.name
        record: Record = {"configuration": configuration.name}
        selection = configuration.selection

        def execute(
            output: Path = output,
            record: Record = record,
            selection: RustSelection | PythonSelection | ScriptRunner = selection,
        ) -> None:
            _fresh(output)
            if isinstance(selection, RustSelection):
                _rust(root, policy, output, selection, (category, coverage), record)
            elif isinstance(selection, PythonSelection):
                _python(root, policy, output, selection, (category, coverage), record)
            else:
                _script(root, policy, output, selection, category, record)

        failure = _attempt(execute)
        record["success"] = failure is None
        record["error"] = _message(failure)
        records.append(record)
        if failure is not None:
            failures.append(f"{configuration.name}: {failure}")
    if failures:
        raise EvidenceError("\n".join(failures))


def _rust(
    root: Path,
    policy: Policy,
    output: Path,
    selection: RustSelection,
    mode: tuple[str, bool],
    record: Record,
) -> None:
    category, coverage = mode
    environment = dict(os.environ)
    if coverage:
        target = root / "target/validation/cargo/coverage"
        environment["CARGO_TARGET_DIR"] = str(target)
        environment["CARGO_LLVM_COV_TARGET_DIR"] = str(target)
        environment["CARGO_LLVM_COV_BUILD_DIR"] = str(target)
    metadata = {} if category == "unit" else _metadata(root)
    selected = narrowed(rust_filter(metadata, category, selection), selection)
    native = output / "nextest.toml"
    native.write_text(
        nextest_config((output / "junit.xml").as_posix(), category, policy, coverage),
        encoding="utf-8",
    )
    started = time.monotonic()
    host_only = ["--coverage-host-only"] if selection.coverage_host_only else []
    runner = (
        ["cargo", "llvm-cov", "nextest", "--no-report", *host_only]
        if coverage
        else ["cargo", "nextest", "run"]
    )
    units = ["--lib", "--bins"] if category == "unit" else []
    runner += [
        *cargo_selection(selection),
        *units,
        "--config-file",
        str(native),
        "--profile",
        "stkr",
        "--no-tests",
        "fail",
        "-E",
        selected,
    ]
    listing = [
        "cargo",
        "nextest",
        "list",
        "--message-format",
        "json",
        *cargo_selection(selection),
        *units,
        "-E",
        selected,
    ]
    inventory_environment = dict(environment)
    if coverage:
        shown = subprocess.run(
            _command(["cargo", "llvm-cov", "show-env", "--cmd", *host_only]),
            cwd=root,
            env=environment,
            capture_output=True,
            text=True,
            check=False,
        )
        if shown.returncode != 0:
            raise EvidenceError(f"coverage inventory setup failed: {shown.stderr}")
        inventory_environment.update(coverage_environment(shown.stdout))
    listed = subprocess.run(
        _command(listing),
        cwd=root,
        env=inventory_environment,
        capture_output=True,
        check=False,
    )
    (output / "inventory.json").write_bytes(listed.stdout)
    if listed.returncode != 0:
        raise EvidenceError(
            "compiled test inventory failed: " + listed.stderr.decode(errors="replace")
        )
    passed = _execute(runner, root, environment=environment)
    # Reporting is attempted even when the test command fails.
    report_errors = []
    if coverage:
        cobertura = output / "coverage.xml"
        exported = _attempt(
            lambda: _execute(
                [
                    "cargo",
                    "llvm-cov",
                    "report",
                    "--cobertura",
                    "--ignore-filename-regex",
                    "(/tests/|/benches/|/fixtures/)",
                    "--output-path",
                    str(cobertura),
                ],
                root,
                environment=environment,
            )
        )
        if exported is not True:
            report_errors.append(f"coverage export: {exported}")
        html = _attempt(
            lambda: _execute(
                [
                    "cargo",
                    "llvm-cov",
                    "report",
                    "--html",
                    "--output-dir",
                    str(output / "html"),
                    "--ignore-filename-regex",
                    "(/tests/|/benches/|/fixtures/)",
                ],
                root,
                environment=environment,
            )
        )
        if html is not True:
            report_errors.append(f"coverage HTML export: {html}")
        checked = _attempt(
            lambda: validate_coverage(_read(cobertura, "coverage report"))
        )
        if checked is not None:
            report_errors.append(str(checked))
    summary = _attempt(
        lambda: summarize(
            _read(output / "junit.xml", "JUnit report"), category, coverage
        )
    )
    # Documentation Tests Follow The Shared Policy In Full Integration Runs
    full = selection.filter is None and not selection.targets
    members = set(metadata.get("workspace_members", []))
    doc_packages = (
        [
            package["name"]
            for package in metadata.get("packages", [])
            if (not members or package.get("id") in members)
            and package["name"] not in selection.exclude
            and (not selection.packages or package["name"] in selection.packages)
            and _docs_version(package.get("version", ""), _config(root).get("docs", {}))
            and any(
                target.get("doctest", True) and "lib" in target.get("kind", [])
                for target in package.get("targets", [])
            )
        ]
        if category == "integration" and full
        else []
    )
    docs: object = True
    if doc_packages:
        arguments = ["--locked"]
        for package in doc_packages:
            arguments += ["--package", package]
        if selection.all_features:
            arguments.append("--all-features")
        if selection.no_default_features:
            arguments.append("--no-default-features")
        if selection.features:
            arguments += ["--features", ",".join(selection.features)]
        docs = _attempt(lambda: _execute(["cargo", "test", "--doc", *arguments], root))
    record["source_scope"] = (
        "workspace authored Rust sources; tests, benches, and fixtures excluded"
    )
    record["selection"] = asdict(selection)
    record["elapsed_seconds_including_build"] = time.monotonic() - started
    record["summary"] = None if isinstance(summary, EvidenceError) else summary
    record["junit_error"] = _message(summary)
    record["doctests_passed"] = docs is True if doc_packages else None
    record["doctests_run"] = bool(doc_packages)
    record["doctest_packages"] = doc_packages
    record["doctest_coverage"] = "not measured"
    record["report_errors"] = report_errors
    if not passed:
        raise EvidenceError("test runner failed; reports retained")
    if report_errors:
        raise EvidenceError("\n".join(report_errors))
    if isinstance(summary, EvidenceError):
        raise summary
    if summary["failed"]:
        raise EvidenceError("JUnit records failed tests")
    for test in summary["slow"]:
        print(
            f"slow test: {json.dumps(test)}; inspect setup, waits, and classification without "
            "reducing coverage",
            file=sys.stderr,
        )
    if docs is not True:
        raise EvidenceError("doctests failed; reports retained")


def _python(
    root: Path,
    policy: Policy,
    output: Path,
    selection: PythonSelection,
    mode: tuple[str, bool],
    record: Record,
) -> None:
    category, coverage = mode
    record["selection"] = asdict(selection)
    factor = COVERAGE_FACTOR if coverage else 1
    timeout = timeout_seconds(policy, category) * factor
    project = root / selection.project
    try:
        manifest = tomllib.loads(_read(project / "pyproject.toml", "Python project"))
    except tomllib.TOMLDecodeError as error:
        raise EvidenceError(f"invalid pyproject.toml: {error}") from error
    native = manifest.get("build-system", {}).get("build-backend") == "maturin"
    preinstalled = selection.install == "preinstalled"
    # A preinstalled wheel was built elsewhere, so its native code cannot be instrumented.
    instrument = coverage and native and not preinstalled
    profile = (
        selection.native_profile
        or manifest.get("tool", {}).get("maturin", {}).get("profile")
        or "release"
    )
    suite = project / "tests" / category
    if not suite.is_dir():
        raise EvidenceError(f"missing Python suite {suite}")
    cobertura = output / "coverage.xml"
    native_cobertura = output / "native-coverage.xml"
    started = time.monotonic()
    scratch = output / "runtime"
    scratch.mkdir(parents=True, exist_ok=True)
    if preinstalled:
        command = ["uv", "run", "--no-sync"]
    else:
        command = ["uv", "run", "--locked", "--group", "test"]
        if native:
            command += ["--config-setting", f"build-args=--profile {profile}"]
        if category == "acceptance":
            command.append("--no-editable")
    command += [
        "python",
        "-m",
        "pytest",
        "--strict-config",
        "--strict-markers",
        "--import-mode=importlib",
        "--timeout-method=thread",
        f"--timeout={timeout}",
        f"--junitxml={output / 'junit.xml'}",
    ]
    if selection.filter is not None:
        command += ["-k", selection.filter]
    command.append(str(suite))
    environment = dict(os.environ)
    # An ambient pytest selection must not silently narrow a required suite.
    environment.pop("PYTEST_ADDOPTS", None)
    environment.pop("COVERAGE_PROCESS_START", None)
    environment["UV_PROJECT_ENVIRONMENT"] = str(root / ".venv")
    if coverage:
        sources = (
            _python_packages(project, selection.sources)
            if category == "acceptance" or preinstalled
            else list(selection.sources)
        )
        command += [f"--cov={source}" for source in sources]
        command.append(f"--cov-report=xml:{cobertura}")
        environment["COVERAGE_FILE"] = str(output / ".coverage")
    native_target = scratch / "native-target"
    native_environment: list[tuple[str, str]] = []
    rust_policy = policy.rust[0].selection
    host_only = (
        ["--coverage-host-only"]
        if isinstance(rust_policy, RustSelection) and rust_policy.coverage_host_only
        else []
    )
    if instrument:
        setup = dict(os.environ, CARGO_TARGET_DIR=str(native_target))
        setup.pop("RUSTC_WRAPPER", None)
        shown = subprocess.run(
            _command(["cargo", "llvm-cov", "show-env", "--cmd", *host_only]),
            cwd=project,
            env=setup,
            capture_output=True,
            text=True,
            check=False,
        )
        if shown.returncode != 0:
            raise EvidenceError(f"native coverage setup failed: {shown.stderr}")
        native_environment = coverage_environment(shown.stdout)
        environment.update(native_environment)
        environment["CARGO_TARGET_DIR"] = str(native_target)
        environment["UV_CACHE_DIR"] = str(scratch / "uv-cache")
    record["install"] = selection.install
    record["installed_distribution"] = (
        _installed(project, manifest, environment) if preinstalled else None
    )
    passed = _execute(command, project, environment)
    summary = _attempt(
        lambda: summarize(
            _read(output / "junit.xml", "JUnit report"), category, coverage
        )
    )
    errors = []
    if coverage:
        normalized = _attempt(
            lambda: _normalize(root, project, selection.sources, cobertura)
        )
        if normalized is not None:
            errors.append(str(normalized))
        checked = _attempt(
            lambda: validate_coverage(_read(cobertura, "coverage report"))
        )
        if checked is not None:
            errors.append(str(checked))
    if instrument:
        exported = _attempt(
            lambda: _execute(
                [
                    "cargo",
                    "llvm-cov",
                    "report",
                    "--cobertura",
                    "--profile",
                    profile,
                    "--output-path",
                    str(native_cobertura),
                ],
                project,
                dict(
                    os.environ,
                    **dict(native_environment),
                    CARGO_TARGET_DIR=str(native_target),
                ),
            )
        )
        if exported is not True:
            errors.append(f"native coverage export: {exported}")
        checked = _attempt(
            lambda: validate_coverage(_read(native_cobertura, "coverage report"))
        )
        if checked is not None:
            errors.append(str(checked))
    record["source_scope"] = list(selection.sources)
    record["native_instrumented"] = instrument
    record["native_profile"] = profile if native and not preinstalled else None
    record["elapsed_seconds_including_build"] = time.monotonic() - started
    record["summary"] = None if isinstance(summary, EvidenceError) else summary
    record["junit_error"] = _message(summary)
    record["report_errors"] = errors
    if not passed:
        raise EvidenceError("pytest failed; reports retained")
    if errors:
        raise EvidenceError("\n".join(errors))
    if isinstance(summary, EvidenceError):
        raise summary
    if summary["failed"]:
        raise EvidenceError("JUnit records failed tests")


def _read(path: Path, description: str) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise EvidenceError(
            f"read required {description} {path}: {error.strerror}"
        ) from error


def _installed(
    project: Path, manifest: dict[str, Any], environment: dict[str, str]
) -> Record:
    """The project distribution an earlier step installed; editable installs are refused."""
    name = manifest.get("project", {}).get("name")
    if not isinstance(name, str) or not name:
        raise EvidenceError("a preinstalled Python project needs [project] name")
    try:
        result = subprocess.run(
            _command(["uv", "run", "--no-sync", "python", "-c", INSTALLED_PROBE, name]),
            cwd=project,
            env=environment,
            capture_output=True,
            text=True,
            timeout=COMMAND_TIMEOUT_SECONDS * 6,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise EvidenceError(f"inspect installed {name}: {error}") from error
    if result.returncode != 0:
        raise EvidenceError(
            f"{name} is not installed in the shared environment; run the step that "
            "installs the wheel first"
        )
    try:
        version, origin = json.loads(result.stdout)
    except (ValueError, TypeError) as error:
        raise EvidenceError(f"inspect installed {name}: {error}") from error
    if isinstance(origin, dict) and origin.get("dir_info", {}).get("editable"):
        raise EvidenceError(f"{name} is installed editable, not as a built wheel")
    url = origin.get("url") if isinstance(origin, dict) else None
    return {"name": name, "version": version, "url": url}


def _script(
    root: Path,
    policy: Policy,
    output: Path,
    runner: ScriptRunner,
    category: str,
    record: Record,
) -> None:
    """Run a script test command whose JUnit lands in the module-owned output."""
    deadline = timeout_seconds(policy, category)
    junit = output / "junit.xml"
    command = [
        argument.replace(JUNIT_PLACEHOLDER, str(junit)).replace(
            TIMEOUT_PLACEHOLDER, str(deadline * 1000)
        )
        for argument in runner.command
    ]
    started = time.monotonic()
    record["selection"] = asdict(runner)
    passed = _execute_bounded(command, root / runner.directory, runner.timeout_seconds)
    record["elapsed_seconds_including_build"] = time.monotonic() - started
    summary = _attempt(lambda: summarize(_read(junit, "JUnit report"), category, False))
    record["summary"] = None if isinstance(summary, EvidenceError) else summary
    record["junit_error"] = _message(summary)
    overrun = _attempt(lambda: _overruns(_read(junit, "JUnit report"), deadline))
    record["deadline_overruns"] = overrun if isinstance(overrun, list) else []
    record["coverage"] = "not measured"
    if passed is None:
        raise EvidenceError(
            f"runner exceeded {runner.timeout_seconds} s and was stopped; reports retained"
        )
    if not passed:
        raise EvidenceError("test runner failed; reports retained")
    if isinstance(summary, EvidenceError):
        raise summary
    if summary["failed"]:
        raise EvidenceError("JUnit records failed tests")
    if record["deadline_overruns"]:
        raise EvidenceError(
            f"tests exceeded the {deadline} s per-test deadline: "
            + ", ".join(record["deadline_overruns"])
        )


def _overruns(text: str, deadline: int) -> list[str]:
    """Cases whose recorded duration exceeds the per-test deadline."""
    names = []
    for case in _testcases(_parse(text)):
        try:
            seconds = float(case.get("time", "0"))
        except ValueError:
            continue
        if seconds > deadline:
            names.append(case.get("name", ""))
    return names


def _execute_bounded(
    arguments: Sequence[str], cwd: Path, timeout: int | None
) -> bool | None:
    """Run a command in its own process group; None when the bound stopped it."""
    try:
        if sys.platform == "win32":
            process = subprocess.Popen(
                _command(arguments),
                cwd=cwd,
                creationflags=subprocess.CREATE_NEW_PROCESS_GROUP,
            )
        else:
            process = subprocess.Popen(
                _command(arguments), cwd=cwd, start_new_session=True
            )
    except OSError as error:
        raise EvidenceError(f"execute {arguments[0]}: {error}") from error
    try:
        return process.wait(timeout=timeout) == 0
    except subprocess.TimeoutExpired:
        # Package-manager shims leave the runner as a child; stop the whole group.
        if sys.platform == "win32":
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(process.pid)],
                capture_output=True,
                check=False,
            )
        else:
            os.killpg(process.pid, signal.SIGKILL)
        process.wait()
        return None


def _python_packages(project: Path, sources: Sequence[str]) -> list[str]:
    """Importable packages below the declared roots, for installed acceptance coverage."""
    packages: set[str] = set()
    for source in sources:
        path = project / source
        if (path / "__init__.py").is_file():
            packages.add(path.name)
            continue
        for entry in path.iterdir():
            if entry.is_dir() and entry.name != "__pycache__":
                packages.add(entry.name)
            elif entry.suffix == ".py":
                packages.add(entry.stem)
    if not packages:
        raise EvidenceError("no Python packages found under declared coverage sources")
    return sorted(packages)


def _normalize(root: Path, project: Path, sources: Sequence[str], path: Path) -> None:
    """Normalize installed-wheel filenames back to declared authored source paths."""
    authored = []
    for source in sources:
        for file in sorted((project / source).rglob("*.py")):
            if not file.is_file():
                continue
            relative = file.relative_to(project).as_posix()
            suffix = relative
            for prefix in ("src/", "python/"):
                if relative.startswith(prefix):
                    suffix = relative.removeprefix(prefix)
                    break
            authored.append((suffix, file.relative_to(root).as_posix()))
    text = normalize_python_paths(
        _read(path, "Python coverage paths"), root.as_posix(), authored
    )
    path.write_text(text, encoding="utf-8")


def _bench_rust(root: Path, log: Path) -> list[Row]:
    metadata = _metadata(root)
    home = os.environ.get("CRITERION_HOME")
    output = Path(home) if home else Path(metadata["target_directory"]) / "criterion"
    members = set(metadata.get("workspace_members", []))
    rows = []
    for package in metadata.get("packages", []):
        if members and package.get("id") not in members:
            continue
        for target in package.get("targets", []):
            if "bench" not in target.get("kind", []):
                continue
            since = time.time()
            _tee(
                [
                    "cargo",
                    "bench",
                    "--locked",
                    "--package",
                    package["name"],
                    "--bench",
                    target["name"],
                ],
                root,
                log,
                f"Rust {target['name']}",
            )
            rows.extend(_criterion(output, target["name"], since))
    if not rows:
        raise EvidenceError("no Criterion results were produced")
    return rows


def _bench_python(root: Path, policy: Policy, log: Path) -> list[Row]:
    selection = policy.python[0].selection
    project = root / (
        selection.project if isinstance(selection, PythonSelection) else "."
    )
    if not (project / "benchmarks").is_dir():
        raise EvidenceError(f"missing Python benchmarks {project / 'benchmarks'}")
    raw = root / "target" / "validation" / "bench"
    raw.mkdir(parents=True, exist_ok=True)
    report = raw / "python.json"
    report.unlink(missing_ok=True)
    environment = dict(os.environ, UV_PROJECT_ENVIRONMENT=str(root / ".venv"))
    environment.pop("PYTEST_ADDOPTS", None)
    _tee(
        [
            "uv",
            "run",
            "--locked",
            "--group",
            "test",
            "python",
            "-m",
            "pytest",
            "--strict-config",
            "--strict-markers",
            "--import-mode=importlib",
            "--benchmark-only",
            "--benchmark-save-data",
            f"--benchmark-json={report}",
            "benchmarks",
        ],
        project,
        log,
        "Python",
        environment,
    )
    return pytest_benchmark(_read(report, "benchmark results"))


def _tee(
    arguments: Sequence[str],
    cwd: Path,
    log: Path,
    section: str,
    environment: dict[str, str] | None = None,
) -> None:
    """Run a command, mirroring its output to the terminal and a titled log section."""
    command = _command(arguments)
    with log.open("ab") as file:
        file.write(f"== {section} ==\n$ {' '.join(arguments)}\n".encode())
        file.flush()
        process = subprocess.Popen(
            command,
            cwd=cwd,
            env=environment,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        guard = threading.Lock()

        def copy(source: IO[bytes], terminal: IO[bytes]) -> None:
            for chunk in iter(lambda: os.read(source.fileno(), 8192), b""):
                terminal.write(chunk)
                terminal.flush()
                with guard:
                    file.write(chunk)

        threads = [
            threading.Thread(target=copy, args=(process.stdout, sys.stdout.buffer)),
            threading.Thread(target=copy, args=(process.stderr, sys.stderr.buffer)),
        ]
        for thread in threads:
            thread.start()
        status = process.wait()
        for thread in threads:
            thread.join()
    if status != 0:
        raise EvidenceError(
            f"benchmark section {section} failed with {status}; see {log}"
        )


def _criterion(output: Path, domain: str, since: float) -> list[Row]:
    """Read the Criterion results written for one bench target since it started."""
    rows = []
    if output.is_dir():
        for path in output.rglob("benchmark.json"):
            if path.parent.name != "new" or path.stat().st_mtime < since:
                continue

            def load(name: str, directory: Path = path.parent) -> Record:
                try:
                    return json.loads(_read(directory / name, "Criterion result"))
                except json.JSONDecodeError as error:
                    raise EvidenceError(f"invalid Criterion {name}: {error}") from error

            rows.append(
                criterion_row(
                    domain,
                    load("benchmark.json"),
                    load("estimates.json"),
                    load("sample.json"),
                )
            )
    rows.sort(key=lambda row: row.name)
    return rows


