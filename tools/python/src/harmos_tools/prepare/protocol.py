def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[5]
    schema = root / "crates/harmos-protocol/proto/sidecar.proto"
    destination = root / "sdk/go/wire"

    # Generate With The Repository's Pinned Native Tools.
    with tempfile.TemporaryDirectory(prefix="harmos-protocol-") as scratch:
        output = Path(scratch)
        subprocess.run(
            [
                "protoc",
                f"--proto_path={schema.parent}",
                f"--go_out={output}",
                "--go_opt=paths=source_relative",
                f"--go-grpc_out={output}",
                "--go-grpc_opt=paths=source_relative",
                schema.name,
            ],
            check=True,
        )
        source = schema.read_text(encoding="utf-8").replace("\r\n", "\n")
        fingerprint = hashlib.sha256(source.encode()).digest()
        values = ", ".join(f"0x{value:02x}" for value in fingerprint)
        identity = f"// Code generated by prepare:protocol. DO NOT EDIT.\npackage wire\n\nvar SchemaFingerprint = [32]byte{{{values}}}\n"
        (output / "schema.go").write_text(identity, encoding="utf-8", newline="\n")
        subprocess.run(["gofmt", "-w", str(output / "schema.go")], check=True)

        # Check Or Replace The Generated Outputs Together.
        if not arguments.check:
            destination.mkdir(parents=True, exist_ok=True)
        for generated in sorted(output.glob("*.go")):
            target = destination / generated.name
            content = generated.read_text(encoding="utf-8")
            if arguments.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    raise SystemExit(f"stale generated protocol: {target.relative_to(root)}")
            else:
                target.write_text(content, encoding="utf-8", newline="\n")


# === Private Functions === #

# === Entry Point === #

if __name__ == "__main__":
    main()
