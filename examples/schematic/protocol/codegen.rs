/// Generate the Example's Authoritative Contracts.
pub fn generate(root: &Path, compiler: &Path, includes: &Path, output: &Path) -> Result<(), Box<dyn Error>> {
    let proto = root.join("proto");
    let core = root.join("../../proto");
    let mut config = Config::new();
    config.protoc_executable(compiler);
    config.out_dir(output);
    config.extern_path(".harmos.model.v1", "::harmos_protocol::model");
    config.file_descriptor_set_path(output.join("schematic.descriptors.bin"));
    config.compile_protos(
        &[proto.join("schematic/v1/operations.proto"), proto.join("schematic/v1/files.proto"), proto.join("schematic/v1/uploads.proto")],
        &[proto, core, includes.into()],
    )?;
    let mut descriptors: FileDescriptorSet = Message::decode(fs::read(output.join("schematic.descriptors.bin"))?.as_slice())?;
    for file in &mut descriptors.file {
        file.source_code_info = None;
    }
    fs::write(output.join("schematic.descriptors.bin"), Message::encode_to_vec(&descriptors))?;
    let mut reflection = String::from(
        "// This file is @generated by the protocol generator.\n#[cfg(feature = \"sdk\")]\nuse prost::Message as ProstMessage;\n#[cfg(feature = \"sdk\")]\nuse prost_types::FileDescriptorSet;\nuse prost_reflect::{MessageDescriptor, ReflectMessage};\n",
    );
    for file in descriptors.file.iter().filter(|file| file.package.as_deref() == Some("schematic.v1")) {
        for message in &file.message_type {
            let name = message.name.as_deref().ok_or("missing example message name")?;
            reflection.push_str(&format!("impl ReflectMessage for super::{name} {{\n    fn descriptor(&self) -> MessageDescriptor {{\n        super::pool().get_message_by_name(\"schematic.v1.{name}\").expect(\"generated example message\")\n    }}\n}}\n"));
            let types = harmos_protocol::schema::operation_types(&descriptors, &[&format!("schematic.v1.{name}")])?;
            let encoded = Message::encode_to_vec(&types).iter().map(|byte| format!("\\x{byte:02x}")).collect::<String>();
            reflection.push_str(&format!("#[cfg(feature = \"sdk\")]\nimpl harmos::Message for super::{name} {{\n    fn name() -> String {{ \"schematic.v1.{name}\".into() }}\n    fn types() -> FileDescriptorSet {{\n        ProstMessage::decode(&b\"{encoded}\"[..]).expect(\"generated example graph\")\n    }}\n}}\n"));
        }
    }
    fs::write(output.join("schematic.reflection.rs"), reflection)?;
    Ok(())
}

