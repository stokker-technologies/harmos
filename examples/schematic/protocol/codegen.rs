/// Generate the Example's Authoritative Contracts.
pub fn generate(root: &Path, compiler: &Path, includes: &Path, output: &Path) -> Result<(), Box<dyn Error>> {
    let proto = root.join("proto");
    let core = root.join("../../proto");
    let mut config = Config::new();
    config.protoc_executable(compiler);
    config.out_dir(output);
    config.skip_source_info();
    config.extern_path(".harmos.model.v1", "::harmos_protocol::model");
    config.file_descriptor_set_path(output.join("schematic.descriptors.bin"));
    config.compile_protos(
        &[
            proto.join("schematic/host/v1/schematic.proto"),
            proto.join("schematic/host/v1/files.proto"),
            proto.join("schematic/host/v1/uploads.proto"),
            proto.join("schematic/plugin/v1/schematic.proto"),
        ],
        &[proto, core, includes.into()],
    )?;
    let descriptors: FileDescriptorSet = Message::decode(fs::read(output.join("schematic.descriptors.bin"))?.as_slice())?;
    // Read the Same Product Composition Used by Runtime Assembly.
    let composition_path = root.join("protocol/composition.toml");
    let composition = fs::read_to_string(&composition_path)?.parse::<DocumentMut>()?;
    let application = DescriptorPool::decode(fs::read(output.join("schematic.descriptors.bin"))?.as_slice())?;
    let mut pools = vec![application];
    if let Some(libraries) = composition.get("libraries") {
        let libraries = libraries.as_array_of_tables().ok_or("Generate Schematic Client: Invalid Libraries")?;
        for library in libraries {
            let path = library
                .get("descriptors")
                .and_then(toml_edit::Item::as_str)
                .ok_or("Generate Schematic Client: Missing Library Descriptors")?;
            let library_path = composition_path.parent().ok_or("Generate Schematic Client: Missing Composition Directory")?.join(path);
            let pool = DescriptorPool::decode(fs::read(library_path)?.as_slice())?;
            let packages =
                library.get("packages").and_then(toml_edit::Item::as_array).ok_or("Generate Schematic Client: Missing Library Packages")?;
            for package in packages {
                let package = package.as_str().ok_or("Generate Schematic Client: Invalid Library Package")?;
                if !pool.files().any(|file| file.package_name() == package) {
                    return Err(format!("Generate Schematic Client: Library Package {package} Is Missing").into());
                }
            }
            pools.push(pool);
        }
    }
    let mut callers = BTreeMap::new();
    for pool in &pools {
        for service in pool.services() {
            for method in service.methods() {
                let id = format!("{}/{}", service.full_name(), method.name());
                callers.insert(id, harmos_protocol::schema::method_callers(&method)?);
            }
        }
    }
    if let Some(restrictions) = composition.get("callers") {
        let restrictions = restrictions.as_table().ok_or("Generate Schematic Client: Invalid Callers")?;
        for (id, value) in restrictions {
            let selected = match value.as_str() {
                Some("CLIENTS") => Callers::Clients,
                Some("PLUGINS") => Callers::Plugins,
                Some("ALL") => Callers::All,
                _ => return Err(format!("Generate Schematic Client: Invalid Callers for {id}").into()),
            };
            let declared = callers.get_mut(id).ok_or_else(|| format!("Generate Schematic Client: Unknown Operation {id}"))?;
            if selected as i32 & *declared as i32 != selected as i32 {
                return Err(format!("Generate Schematic Client: Cannot Widen Callers for {id}").into());
            }
            *declared = selected;
        }
    }

    let mut reflection = String::from(
        "// This file is @generated by the protocol generator.\n#[cfg(feature = \"sdk\")]\nuse prost::Message as ProstMessage;\n#[cfg(feature = \"sdk\")]\nuse prost_types::FileDescriptorSet;\nuse prost_reflect::{MessageDescriptor, ReflectMessage};\n",
    );
    for file in descriptors.file.iter().filter(|file| file.package.as_deref().is_some_and(|package| package.starts_with("schematic."))) {
        let package = file.package.as_deref().ok_or("missing example package")?;
        for message in &file.message_type {
            let name = message.name.as_deref().ok_or("missing example message name")?;
            let location = if package == "schematic.plugin.v1" { format!("super::plugin::{name}") } else { format!("super::{name}") };
            reflection.push_str(&format!("impl ReflectMessage for {location} {{\n    fn descriptor(&self) -> MessageDescriptor {{\n        super::pool().get_message_by_name(\"{package}.{name}\").expect(\"generated example message\")\n    }}\n}}\n"));
            let types = harmos_protocol::schema::operation_types(&descriptors, &[&format!("{package}.{name}")])?;
            let encoded = Message::encode_to_vec(&types).iter().map(|byte| format!("\\x{byte:02x}")).collect::<String>();
            reflection.push_str(&format!("#[cfg(feature = \"sdk\")]\nimpl harmos::Message for {location} {{\n    fn name() -> String {{ \"{package}.{name}\".into() }}\n    fn types() -> FileDescriptorSet {{\n        ProstMessage::decode(&b\"{encoded}\"[..]).expect(\"generated example graph\")\n    }}\n}}\n"));
        }
    }
    fs::write(output.join("schematic.reflection.rs"), reflection)?;
    // Generate the Application's Unary Advice Client From Its Declared Service.
    let service = descriptors
        .file
        .iter()
        .filter(|file| file.package.as_deref() == Some("schematic.host.v1"))
        .flat_map(|file| &file.service)
        .find(|service| service.name.as_deref() == Some("Schematic"))
        .ok_or("Generate Schematic Client: Missing Schematic Service")?;
    let mut client = String::from(
        "// @generated from schematic protocol descriptors; do not edit.\nuse harmos::client::{CallOptions, ClientTransport, action_error};\nuse prost_reflect::ReflectMessage;\nuse tonic::{Status, codegen::http::uri::PathAndQuery};\n#[derive(Clone)]\npub struct Client { pub schematic: Schematic }\nimpl Client { pub fn new(transport: ClientTransport) -> Self { Self { schematic: Schematic { transport } } } }\n#[derive(Clone)]\npub struct Schematic { transport: ClientTransport }\n",
    );
    let mut imports = BTreeSet::new();
    for (method, name, arguments, request, response, value, result, payload) in [
        (
            "Validate",
            "validate",
            "schematic: Snapshot",
            "SchematicValidateRequest",
            "SchematicValidateResponse",
            "SchematicValidateRequest { schematic: Some(schematic) }",
            "Vec<String>",
            "diagnostics",
        ),
        (
            "ProposeRoute",
            "propose_route",
            "from: Point, to: Point",
            "SchematicProposeRouteRequest",
            "SchematicProposeRouteResponse",
            "SchematicProposeRouteRequest { from: Some(from), to: Some(to) }",
            "Vec<Point>",
            "points",
        ),
        (
            "ListDirectories",
            "list_directories",
            "",
            "SchematicListDirectoriesRequest",
            "SchematicListDirectoriesResponse",
            "SchematicListDirectoriesRequest {}",
            "Vec<String>",
            "directories",
        ),
    ] {
        if !service.method.iter().any(|declaration| declaration.name.as_deref() == Some(method)) {
            return Err(format!("Generate Schematic Client: Missing {method}").into());
        }
        let id = format!("schematic.host.v1.Schematic/{method}");
        if !matches!(callers.get(&id), Some(Callers::Clients | Callers::All)) {
            continue;
        }
        imports.extend([request, response]);
        if arguments.contains("Snapshot") {
            imports.insert("Snapshot");
        }
        if arguments.contains("Point") {
            imports.insert("Point");
        }
        let separator = if arguments.is_empty() { "" } else { ", " };
        client.push_str(&format!("impl Schematic {{ pub async fn {name}(&self{separator}{arguments}) -> Result<{result}, Status> {{ let request = CallOptions::default().request({value}); let response = self.transport.unary::<{request}, {response}>(PathAndQuery::from_static(\"/schematic.host.v1.Schematic/{method}\"), request, {response}::default().descriptor()).await.map_err(|error| action_error(\"schematic.{name}\", error))?; Ok(response.into_inner().{payload}) }} }}\n"));
    }
    client.push_str(&format!("use crate::{{{}}};\n", imports.into_iter().collect::<Vec<_>>().join(", ")));
    let client_path = output.join("schematic.client.rs");
    fs::write(&client_path, client)?;
    let formatted = Command::new("rustfmt").args(["--edition", "2024"]).arg(&client_path).status()?;
    if !formatted.success() {
        return Err("Generate Schematic Client: Format Failed".into());
    }

    Ok(())
}

