fn collect(items: Vec<Item>, module: &str, payloads: &mut BTreeMap<String, Payload>) {
    for item in items {
        match item {
            Item::Mod(item) => {
                if let Some((_, items)) = item.content {
                    collect(items, &format!("{module}::{}", item.ident), payloads);
                }
            }
            Item::Struct(item) if item.attrs.iter().any(|attr| attr.to_token_stream().to_string().contains("prost :: Message")) => {
                let fields =
                    item.fields.into_iter().map(|field| (field.ident.expect("named message field").to_string(), field.ty)).collect();
                payloads.insert(format!("{module}::{}", item.ident), Payload { fields, variants: false });
            }
            Item::Enum(item) if item.attrs.iter().any(|attr| attr.to_token_stream().to_string().contains("prost :: Oneof")) => {
                let fields = item
                    .variants
                    .into_iter()
                    .map(|variant| (variant.ident.to_string(), variant.fields.into_iter().next().expect("oneof payload").ty))
                    .collect();
                payloads.insert(format!("{module}::{}", item.ident), Payload { fields, variants: true });
            }
            _ => {}
        }
    }
}

fn dependencies(field: &Type, module: &str, payloads: &BTreeMap<String, Payload>, pending: &mut Vec<String>) {
    let Type::Path(field) = field else { return };
    let mut parts = field.path.segments.iter().map(|segment| segment.ident.to_string()).collect::<Vec<_>>();
    let name = if parts.first().is_some_and(|part| part == "crate") {
        parts[0] = "harmos_protocol".into();
        parts.join("::")
    } else if field.path.leading_colon.is_some() {
        parts.join("::")
    } else {
        let mut parent = module.to_owned();
        while parts.first().is_some_and(|part| part == "super") {
            parent = parent.rsplit_once("::").expect("parent module").0.to_owned();
            parts.remove(0);
        }
        format!("{parent}::{}", parts.join("::"))
    };
    if payloads.contains_key(&name) {
        pending.push(name);
    }
    for segment in &field.path.segments {
        if let PathArguments::AngleBracketed(arguments) = &segment.arguments {
            for argument in &arguments.args {
                if let GenericArgument::Type(field) = argument {
                    dependencies(field, module, payloads, pending);
                }
            }
        }
    }
}

