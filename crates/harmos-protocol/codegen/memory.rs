pub fn generate(output: &Path, modules: &BTreeMap<String, String>) -> Result<String, Box<dyn Error>> {
    let mut payloads = BTreeMap::new();
    for (package, module) in modules {
        let source = fs::read_to_string(output.join(format!("{package}.rs")))?;
        let source = syn::parse_file(&source)?;
        collect(source.items, &module.replace("crate::", "harmos_protocol::"), &mut payloads);
    }
    // Use the Locked Rust Layout; protoc's Descriptor Schema Can Be Newer Than prost-types.
    let metadata = Command::new("cargo").args(["metadata", "--locked", "--offline", "--format-version", "1"]).output()?;
    if !metadata.status.success() {
        return Err(
            format!("Generate Payload Memory: Resolve the Locked Dependencies: {}", String::from_utf8_lossy(&metadata.stderr)).into()
        );
    }
    let metadata: Value = serde_json::from_slice(&metadata.stdout)?;
    let manifest = metadata["packages"]
        .as_array()
        .ok_or("Generate Payload Memory: Read Cargo Packages")?
        .iter()
        .find(|package| package["name"] == "prost-types")
        .and_then(|package| package["manifest_path"].as_str())
        .ok_or("Generate Payload Memory: Resolve prost-types")?;
    let manifest = PathBuf::from(manifest);
    let source = fs::read_to_string(manifest.parent().ok_or("Generate Payload Memory: Locate prost-types")?.join("src/protobuf.rs"))?;
    let source = syn::parse_file(&source)?;
    collect(source.items, "prost_types", &mut payloads);
    let mut pending: Vec<_> = payloads
        .keys()
        .filter(|name| name.starts_with("harmos_protocol::host::") && (name.ends_with("Request") || name.ends_with("WatchResponse")))
        .cloned()
        .collect();
    let mut selected = BTreeSet::new();
    while let Some(name) = pending.pop() {
        if !selected.insert(name.clone()) {
            continue;
        }
        let payload = payloads.get(&name).ok_or_else(|| format!("Generate Payload Memory: Declare {name}"))?;
        let module = name.rsplit_once("::").expect("qualified payload").0;
        for (_, field) in &payload.fields {
            dependencies(field, module, &payloads, &mut pending);
        }
    }
    let parents: BTreeSet<_> = selected.iter().map(|name| name.rsplit_once("::").expect("qualified payload").0).collect();
    let mut source = String::from(
        "// This file is @generated by the protocol generator.\n#![allow(deprecated, reason = \"Allocation accounting includes retained descriptor fields\")]\nuse std::mem;\nuse crate::MemorySize;\n",
    );
    for parent in parents {
        if parent.contains("::") {
            source.push_str(&format!("use {parent};\n"));
        }
    }
    for name in selected {
        let payload = &payloads[&name];
        let (parent, item) = name.rsplit_once("::").expect("qualified payload");
        let module = parent.rsplit("::").next().expect("payload module");
        source.push_str(&format!("\nimpl MemorySize for {module}::{item} {{\n    fn memory_size(&self) -> usize {{\n"));
        if payload.variants {
            source.push_str("        mem::size_of::<Self>().saturating_add(match self {\n");
            for (field, _) in &payload.fields {
                source.push_str(&format!(
                    "            Self::{field}(value) => value.memory_size().saturating_sub(mem::size_of_val(value)),\n"
                ));
            }
            source.push_str("        })\n");
        } else {
            source.push_str("        mem::size_of::<Self>()\n");
            for (field, _) in &payload.fields {
                source.push_str(&format!(
                    "            .saturating_add(self.{field}.memory_size().saturating_sub(mem::size_of_val(&self.{field})))\n"
                ));
            }
        }
        source.push_str("    }\n}\n");
    }
    Ok(source)
}

