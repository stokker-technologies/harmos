fn main() -> Result<(), Box<dyn Error>> {
    let output = tempfile::tempdir()?;
    codegen::generate(&protoc_bin_vendored::protoc_bin_path()?, &protoc_bin_vendored::include_path()?, output.path())?;
    let destination = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    // Delete Superseded Generated Modules Before Copying the New Inventory.
    let expected: std::collections::BTreeSet<_> = fs::read_dir(output.path())?
        .filter_map(Result::ok)
        .filter_map(|entry| entry.file_name().into_string().ok())
        .filter(|name| name.starts_with("harmos.") && name.ends_with(".rs"))
        .map(|name| {
            codegen::module_path(name.trim_end_matches(".rs")).map(|module| destination.join(format!("{}.rs", module.replace("::", "/"))))
        })
        .collect::<Result<_, _>>()?;
    let mut folders = vec![destination.clone()];
    while let Some(folder) = folders.pop() {
        for entry in fs::read_dir(folder)? {
            let path = entry?.path();
            if path.is_dir() {
                folders.push(path);
                continue;
            }
            if path.extension().is_some_and(|extension| extension == "rs")
                && fs::read_to_string(&path)?.starts_with("// This file is @generated by prost-build.")
                && !expected.contains(&path)
            {
                fs::remove_file(path)?;
            }
        }
    }
    let obsolete = destination.join("client-clock-descriptors.bin");
    if obsolete.exists() {
        fs::remove_file(obsolete)?;
    }
    for entry in fs::read_dir(output.path())? {
        let path = entry?.path();
        let name = path.file_name().ok_or("missing generated name")?.to_string_lossy();
        if name.starts_with("harmos.") && name.ends_with(".rs") {
            let module = codegen::module_path(name.trim_end_matches(".rs"))?;
            let target = destination.join(format!("{}.rs", module.replace("::", "/")));
            fs::create_dir_all(target.parent().ok_or("missing generated parent")?)?;
            fs::copy(path, target)?;
        }
    }
    for name in ["reflection.rs", "descriptors.bin", "guest-descriptors.bin", "clock-descriptors.bin", "message-options-descriptors.bin"] {
        fs::copy(output.path().join(name), destination.join(name))?;
    }
    let destination = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../sdk/rust/src/context/types");
    fs::create_dir_all(&destination)?;
    for entry in fs::read_dir(&destination)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "bin") {
            fs::remove_file(path)?;
        }
    }
    for entry in fs::read_dir(output.path().join("context-types"))? {
        let path = entry?.path();
        fs::copy(&path, destination.join(path.file_name().ok_or("missing context type filename")?))?;
    }
    codegen::generate_client_fixture(&protoc_bin_vendored::protoc_bin_path()?, &protoc_bin_vendored::include_path()?, output.path())?;
    let destination = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../sdk/rust/tests/fixtures/client");
    fs::create_dir_all(&destination)?;
    for entry in fs::read_dir(&destination)? {
        let path = entry?.path();
        if path.file_name().and_then(|name| name.to_str()).is_some_and(|name| name.starts_with("application.v1") && name.ends_with(".rs")) {
            fs::remove_file(path)?;
        }
    }
    for name in [
        "application.host.v1.rs",
        "application.host.v1.jobs.rs",
        "application.host.v1.plugins.rs",
        "client-descriptors.bin",
        "client-reflection.rs",
    ] {
        fs::copy(output.path().join(name), destination.join(name))?;
    }
    codegen::generate_conformance(&protoc_bin_vendored::protoc_bin_path()?, &protoc_bin_vendored::include_path()?, output.path())?;
    let destination = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../sdk/rust/tests/fixtures/conformance");
    fs::create_dir_all(&destination)?;
    for (source, target) in [
        ("conformance.model.v1.rs", "generated.rs"),
        ("conformance-descriptors.bin", "descriptors.bin"),
        ("caller-request.bin", "caller-request.bin"),
    ] {
        fs::copy(output.path().join(source), destination.join(target))?;
    }
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/schematic");
    schematic::generate(&root, &protoc_bin_vendored::protoc_bin_path()?, &protoc_bin_vendored::include_path()?, output.path())?;
    for (source, target) in [
        ("schematic.host.v1.rs", "host.rs"),
        ("schematic.model.v1.rs", "model.rs"),
        ("schematic.plugin.v1.rs", "plugin.rs"),
        ("schematic.client.rs", "client.rs"),
        ("schematic.reflection.rs", "reflection.rs"),
        ("schematic.descriptors.bin", "descriptors.bin"),
    ] {
        fs::copy(output.path().join(source), root.join("protocol/src").join(target))?;
    }
    Ok(())
}

